/**
 * Authoritative state transition matrix for Meeting Lifecycle.
 * Arbitrary status updates are strictly prohibited.
 */
export const ALLOWED_MEETING_TRANSITIONS: Readonly<
  Record<MeetingStatus, readonly MeetingStatus[]>
> = {
  SCHEDULED: [
    MEETING_STATUS.CONFIRMED,
    MEETING_STATUS.CHECKED_IN,
    MEETING_STATUS.RESCHEDULED,
    MEETING_STATUS.CANCELLED,
  ],
  CONFIRMED: [
    MEETING_STATUS.CHECKED_IN,
    MEETING_STATUS.RESCHEDULED,
    MEETING_STATUS.CANCELLED,
  ],
  CHECKED_IN: [
    MEETING_STATUS.IN_PROGRESS,
    MEETING_STATUS.PAUSED,
    MEETING_STATUS.AWAITING_OUTCOME,
    MEETING_STATUS.RESCHEDULED,
  ],
  IN_PROGRESS: [
    MEETING_STATUS.PAUSED,
    MEETING_STATUS.AWAITING_OUTCOME,
    MEETING_STATUS.RESCHEDULED,
  ],
  PAUSED: [
    MEETING_STATUS.IN_PROGRESS,
    MEETING_STATUS.AWAITING_OUTCOME,
    MEETING_STATUS.RESCHEDULED,
  ],
  AWAITING_OUTCOME: [
    MEETING_STATUS.CHECKED_IN,
    MEETING_STATUS.RESCHEDULED,
    MEETING_STATUS.COMPLETED,
  ],
  RESCHEDULED: [
    MEETING_STATUS.CONFIRMED,
    MEETING_STATUS.CHECKED_IN,
    MEETING_STATUS.CANCELLED,
  ],
  COMPLETED: [MEETING_STATUS.REOPENED],
  REOPENED: [
    MEETING_STATUS.CHECKED_IN,
    MEETING_STATUS.IN_PROGRESS,
    MEETING_STATUS.AWAITING_OUTCOME,
    MEETING_STATUS.RESCHEDULED,
    MEETING_STATUS.COMPLETED,
  ],
  CANCELLED: [],
};

export function canTransitionMeetingStatus(
  from: MeetingStatus,
  to: MeetingStatus,
): boolean {
  return ALLOWED_MEETING_TRANSITIONS[from]?.includes(to) ?? false;
}

